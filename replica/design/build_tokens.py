"""tokens.json -> web/app/tokens.css (custom properties) + web/app/theme.css (Tailwind v4 mapping).

    python replica/design/build_tokens.py

Run after every token change. Components use the Tailwind names (bg-surface,
text-muted, rounded-md, text-doc), never raw hex.
"""
import colorsys
import json
import pathlib
import re

from contrast import parse_hex, ratio

HERE = pathlib.Path(__file__).resolve().parent
WEB_APP = HERE.parent.parent / "web" / "app"
HEADER = "/* Generated by replica/design/build_tokens.py from tokens.json. Do not edit. */\n"

t = json.loads((HERE / "tokens.json").read_text(encoding="utf-8"))


# ---------------------------------------------------------------- dark theme
# Chrome is composed by hand ("dark" in tokens.json). Evidence and status colours are derived: keep each
# light colour's hue, lift its lightness until it clears the contrast floors on its own tinted surface.
def to_hex(rgb):
    return "#%02x%02x%02x" % tuple(round(c) for c in rgb)


def mix(a, b, share):
    """share of colour a over colour b."""
    return to_hex(tuple(x * share + y * (1 - share) for x, y in zip(parse_hex(a), parse_hex(b))))


def lift(light, ok):
    """First lightness at or above 0.58 (hue and saturation of `light` kept) for which ok(candidate) holds."""
    h, _, s = colorsys.rgb_to_hls(*(c / 255 for c in parse_hex(light)))
    s = min(s, 0.85)
    for step in range(43):
        cand = to_hex(tuple(c * 255 for c in colorsys.hls_to_rgb(h, 0.58 + step * 0.01, s)))
        if ok(cand):
            return cand
    raise SystemExit(f"no dark value found for {light}")


def derive_dark(light, chrome):
    ground, text, on_match, on_accent = chrome["bg"], chrome["text"], chrome["on-match"], chrome["on-accent"]
    tint = lambda c: mix(c, ground, 0.18)
    out = {}
    # evidence: a solid on its own tint, with on-match text over the solid
    for key in light:
        m = re.fullmatch(r"(match-\d+|ai|ai-paraphrased)-solid", key)
        if m:
            solid = lift(light[key], lambda c: ratio(on_match, c) >= 4.5 and ratio(c, tint(c)) >= 3 and ratio(text, tint(c)) >= 4.5)
            out[key], out[f"{m[1]}-bg"] = solid, tint(solid)
        m = re.fullmatch(r"(score-\w+)-text", key)
        if m:
            fg = lift(light[key], lambda c: ratio(c, tint(c)) >= 4.5)
            out[key], out[f"{m[1]}-bg"] = fg, tint(fg)
    # status: coloured text on the page and on its own surface
    for name in ("danger", "success", "warning", "info"):
        need_fill = name == "danger"  # white-on-danger buttons: on-accent sits on the colour
        fg = lift(light[name], lambda c: ratio(c, ground) >= 4.5 and ratio(c, tint(c)) >= 4.5
                  and ratio(text, tint(c)) >= 4.5 and (not need_fill or ratio(on_accent, c) >= 4.5))
        out[name], out[f"{name}-surface"] = fg, tint(fg)
    return out


dark_theme = {**derive_dark(t["color"], t["dark"]), **t["dark"]}

root, theme = [], ["  --color-*: initial;", "  --spacing: 4px;"]
for name, value in t["color"].items():
    root.append(f"  --{name}: {value};")
    # "text-muted" maps to text-muted / bg-muted, not text-text-muted.
    tw = name[len("text-"):] if name.startswith("text-") else name
    theme.append(f"  --color-{tw}: var(--{name});")
for name, value in t["font"].items():
    root.append(f"  --font-{name}-stack: {value};")
    theme.append(f"  --font-{name}: var(--font-{name}-stack);")
for name, s in t["type"].items():
    root.append(f"  --type-{name}: {s['size']}px;")
    root.append(f"  --type-{name}-line: {s['line']}px;")
    theme.append(f"  --text-{name}: var(--type-{name});")
    theme.append(f"  --text-{name}--line-height: var(--type-{name}-line);")
    theme.append(f"  --text-{name}--font-weight: {s['weight']};")
for name, value in t["radius"].items():
    root.append(f"  --radius-{name}: {value}px;")
    theme.append(f"  --radius-{name}: var(--radius-{name});")
for name, value in t["shadow"].items():
    root.append(f"  --shadow-{name}: {value};")
    theme.append(f"  --shadow-{name}: var(--shadow-{name});")
for name, value in t["motion"].items():
    root.append(f"  --motion-{name}: {value};")
theme.append("  --ease-standard: var(--motion-ease);")
theme.append("  --default-transition-duration: var(--motion-fast);")
theme.append("  --default-transition-timing-function: var(--motion-ease);")
for name, value in t["layout"].items():
    if isinstance(value, (int, float)):
        root.append(f"  --layout-{name}: {value}px;")
        theme.append(f"  --container-{name}: var(--layout-{name});")
for name, value in t["layout"]["breakpoints"].items():
    theme.append(f"  --breakpoint-{name}: {value / 16}rem;")

dark = [f"    --{name}: {value};" for name, value in dark_theme.items()]
# The contrast checker reads one colour map: give it the dark theme as its own file.
(HERE / "tokens.dark.json").write_text(json.dumps({"color": {**t["color"], **dark_theme}, "pairs": t["pairs"]}, indent=1), encoding="utf-8")

WEB_APP.mkdir(parents=True, exist_ok=True)
(WEB_APP / "tokens.css").write_text(
    HEADER + ":root {\n" + "\n".join(root) + "\n}\n"
    + "@media (prefers-color-scheme: dark) {\n  :root {\n" + "\n".join(dark) + "\n  }\n}\n",
    encoding="utf-8")
(WEB_APP / "theme.css").write_text(HEADER + "@theme inline {\n" + "\n".join(theme) + "\n}\n", encoding="utf-8")
print(f"wrote {len(root)} properties to {WEB_APP / 'tokens.css'} and {len(theme)} theme entries to {WEB_APP / 'theme.css'}")
